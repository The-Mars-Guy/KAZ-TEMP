// One-off generator for accurate country silhouettes used by the homepage hero.
// Run with: node scripts/generate-maps.mjs
import fs from "node:fs";
import { geoPath, geoAlbers, geoMercator } from "d3-geo";
import { feature } from "topojson-client";

const worldTopo = JSON.parse(fs.readFileSync("node_modules/world-atlas/countries-110m.json", "utf8"));
const countries = feature(worldTopo, worldTopo.objects.countries);

const usa = countries.features.find((f) => String(f.id) === "840");
if (!usa) throw new Error("USA not found in world-atlas");

// Keep only the contiguous landmass: drop Alaska, Hawaii, and island territories
// by bounding box. (Natural Earth stores the USA as a MultiPolygon.)
const polygons = (usa.geometry.coordinates || []).filter((poly) => {
  const ring = poly[0] || [];
  let minLon = 180, maxLon = -180, minLat = 90, maxLat = -90;
  for (const [lon, lat] of ring) {
    if (lon < minLon) minLon = lon;
    if (lon > maxLon) maxLon = lon;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
  }
  return minLon > -130 && maxLon < -60 && minLat > 24 && maxLat < 50;
});
const contiguous = { type: "Feature", properties: {}, geometry: { type: "MultiPolygon", coordinates: polygons } };

const usProjection = geoAlbers()
  .parallels([29.5, 45.5])
  .rotate([96, 0])
  .center([-0.6, 38.7]);
const usPath = geoPath(usProjection.fitExtent([[10, 10], [790, 490]], contiguous));

const poland = countries.features.find(
  (f) => String(f.id) === "616" || f.properties?.name === "Poland"
);
if (!poland) throw new Error("Poland not found in world-atlas");
const plProjection = geoMercator();
const plPath = geoPath(plProjection.fitExtent([[10, 10], [490, 590]], poland));

const compact = (d) =>
  d
    ? d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10))
    : "";

const out = `// Generated by scripts/generate-maps.mjs — do not edit by hand.
// Accurate Natural Earth geometry, projected to flat silhouettes.
export const US_MAP = {
  viewBox: "0 0 800 500",
  path: ${JSON.stringify(compact(usPath(contiguous)))},
};

export const POLAND_MAP = {
  viewBox: "0 0 500 600",
  path: ${JSON.stringify(compact(plPath(poland)))},
};
`;

fs.writeFileSync("src/assets/maps.js", out, "utf8");
console.log("wrote src/assets/maps.js", out.length, "bytes");
